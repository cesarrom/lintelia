// Summarise the last e2e run per flow id (tags like @FIA-04) into docs/testing/flow-status.md.
// Usage: bun run test (or any subset), then `bun run flow-status`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const report = JSON.parse(readFileSync(join(root, 'test-results/results.json'), 'utf8'));
const output = join(root, '../../docs/testing/flow-status.md');

const FLOW_TAG = /^@([A-Z]+-\d+)$/;
const flows = new Map();

function visit(suite, inheritedTags = []) {
  for (const child of suite.suites ?? []) visit(child, inheritedTags);
  for (const spec of suite.specs ?? []) {
    const tags = [...new Set([...(spec.tags ?? []).map((t) => (t.startsWith('@') ? t : `@${t}`)), ...inheritedTags])];
    const ids = tags.map((t) => t.match(FLOW_TAG)?.[1]).filter(Boolean);
    for (const test of spec.tests ?? []) {
      const status = test.results?.at(-1)?.status ?? 'skipped';
      const error = test.results?.at(-1)?.error?.message?.split('\n')[0]?.replace(/\u001b\[[0-9;]*m/g, '') ?? '';
      for (const id of ids) {
        const flow = flows.get(id) ?? { id, passed: 0, failed: 0, skipped: 0, failures: [] };
        if (status === 'passed') flow.passed += 1;
        else if (status === 'skipped') flow.skipped += 1;
        else {
          flow.failed += 1;
          if (flow.failures.length < 2) flow.failures.push(`${spec.title}: ${error}`.slice(0, 160));
        }
        flows.set(id, flow);
      }
    }
  }
}
for (const suite of report.suites ?? []) visit(suite);

const order = ['STAFF', 'FIA', 'DES', 'REV', 'SUP', 'CMP', 'RM', 'AGT', 'INT', 'AUD', 'CLI', 'APP', 'AUT', 'X', 'SCN'];
const sorted = [...flows.values()].sort((a, b) => {
  const [pa, na] = a.id.split('-');
  const [pb, nb] = b.id.split('-');
  return order.indexOf(pa) - order.indexOf(pb) || Number(na) - Number(nb);
});

// Tests that did not run (their setup failed) count as not working.
const statusOf = (f) => (f.failed === 0 && f.skipped === 0 && f.passed > 0 ? 'works' : f.passed > 0 ? 'partial' : 'planned');
const totals = sorted.reduce((t, f) => ({ ...t, [statusOf(f)]: (t[statusOf(f)] ?? 0) + 1 }), {});
const stats = report.stats ?? {};

const lines = [
  '# Flow status',
  '',
  `Generated by \`bun run --cwd apps/e2e flow-status\` from the last e2e run (${new Date(stats.startTime ?? Date.now()).toISOString()}).`,
  'Flow definitions: [../product/flows.md](../product/flows.md). A flow "works" when all its tests pass.',
  '',
  `Tests: ${stats.expected ?? 0} passed, ${stats.unexpected ?? 0} failed, ${stats.skipped ?? 0} did not run (setup failed). ` +
    `Flows: ${totals.works ?? 0} works, ${totals.partial ?? 0} partial, ${totals.planned ?? 0} planned.`,
  '',
  '| Flow | Status | Passed | Failed | Not run | First failures |',
  '| --- | --- | --- | --- | --- | --- |',
  ...sorted.map((f) => `| ${f.id} | ${statusOf(f)} | ${f.passed} | ${f.failed} | ${f.skipped} | ${f.failures.map((x) => x.replace(/\|/g, '\\|')).join('<br>')} |`),
  '',
];
writeFileSync(output, lines.join('\n'));

// Keep the status column of the flow catalogue (docs/product/flows.md) in sync with the run.
const catalogue = join(root, '../../docs/product/flows.md');
const byId = new Map(sorted.map((f) => [f.id, statusOf(f)]));
const synced = readFileSync(catalogue, 'utf8').replace(/^\| ([A-Z]+-\d+) \| (.+?) \| (works|partial|planned) \| (.*)$/gm,
  (line, id, flow, status, tech) => (byId.has(id) ? `| ${id} | ${flow} | ${byId.get(id)} | ${tech}` : line));
writeFileSync(catalogue, synced);
console.log(`wrote ${output}: ${sorted.length} flows (${totals.works ?? 0} works, ${totals.partial ?? 0} partial, ${totals.planned ?? 0} planned)`);
